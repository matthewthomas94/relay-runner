#!/usr/bin/env python3
"""Generate the Lucide icon data for the Relay Remote iPhone app.

Reuses the desktop generator, scripts/generate-lucide-icons.py: the same
pinned Lucide release, the same SVG validation and the same Swift output, with
the iPhone's own icon list. Writes
ios/RelayRemote/DesignSystem/Lucide/LucideIcons.generated.swift; the renderer is
LucideIcon.swift beside it, a copy of the desktop's.

Usage, from the repository root:
    /opt/homebrew/bin/python3 -I ios/scripts/generate-lucide-icons.py [--cache DIR]
"""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
DESKTOP = ROOT / "scripts/generate-lucide-icons.py"
OUTPUT = ROOT / "ios/RelayRemote/DesignSystem/Lucide/LucideIcons.generated.swift"

# Every icon the iPhone designs use (docs/design/relay-remote-ios), alphabetical.
ICONS = [
    "arrow-right",
    "arrow-up",
    "audio-lines",
    "bell",
    "camera",
    "check",
    "chevron-down",
    "chevron-right",
    "clipboard-paste",
    "key-round",
    "laptop",
    "mic",
    "play",
    "power",
    "qr-code",
    "refresh-cw",
    "rotate-ccw",
    "settings",
    "speech",
    "square",
    "square-kanban",
    "ticket",
    "triangle-exclamation-point",
    "users",
    "wifi",
    "wifi-off",
    "x",
]


def main() -> int:
    sys.dont_write_bytecode = True  # importing the desktop script must not leave scripts/__pycache__
    spec = importlib.util.spec_from_file_location("desktop_lucide", DESKTOP)
    generator = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(generator)
    generator.ICONS = ICONS
    generator.OUTPUT = OUTPUT
    render = generator.render
    generator.render = lambda icons: render(icons).replace(
        "// Generated by scripts/generate-lucide-icons.py.",
        "// Generated by ios/scripts/generate-lucide-icons.py.", 1)
    return generator.main()


if __name__ == "__main__":
    sys.exit(main())
