"""RR-500: the Rust and Python daemons take turns on one data root.

scripts/relay-orchestrator runs the Rust daemon by default and the Python
daemon with RELAY_ORCHESTRATOR_RUNTIME=python, so either may find the other's
databases, runs.json, artifact refs, worktrees and notes. Each case runs one
daemon, stops it, starts the other on the same sandbox, and checks that it
serves what the first one wrote, leaves every database schema as it was (no
migration in either direction), and carries on: run ids continue, merged
work stays merged, sessions and notes are the same objects.

Every case skips when the Rust binary is not built (``cargo build`` in rust/).
"""

from __future__ import annotations

import os
import sqlite3
import sys
import unittest
from pathlib import Path
from unittest import mock

import orchestrator_contract_support as support
from orchestrator_contract_support import ARTIFACT_REF, UPDATE_GOLDEN, Sandbox, git

from test_orchestrator_contract_notes import create_body

REPO = Path(__file__).resolve().parents[2]
RUST_DAEMON = Path(
    os.environ.get("RELAY_RUST_ORCHESTRATOR")
    or REPO / "rust" / "target" / "debug" / "relay-orchestrator"
)
DAEMONS = {
    "python": [sys.executable, str(REPO / "services" / "orchestrator.py")],
    "rust": [str(RUST_DAEMON)],
}


def schemas(data_root: Path) -> dict:
    """Every database's user_version and table columns."""
    result = {}
    for path in sorted(data_root.glob("*.db")):
        connection = sqlite3.connect("file:%s?mode=ro" % path, uri=True)
        try:
            tables = [row[0] for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")]
            result[path.name] = {
                "user_version": connection.execute("PRAGMA user_version").fetchone()[0],
                "columns": {table: [row[1] for row in connection.execute("PRAGMA table_info(%s)" % table)]
                            for table in tables},
            }
        finally:
            connection.close()
    return result


class _SwapCase(unittest.TestCase):
    agent = "claude"
    maxDiff = None

    def setUp(self):
        if UPDATE_GOLDEN:
            self.skipTest("goldens are being regenerated by the reference daemon")
        if not os.access(RUST_DAEMON, os.X_OK):
            self.skipTest("relay-orchestrator is not built; run cargo build in rust/")
        self.box = Sandbox(self.addCleanup, agent=self.agent)
        self.legacy = self.box.make_repo("legacy")
        for number in (1, 2, 3):
            self.box.write_ticket(self.legacy, "CT-%d" % number)
        self.artifact = self.box.artifact_project(
            "artifact", tickets=[("CT-%d" % number, {}) for number in (11, 12, 13)], next_id=14)
        self.session = None
        self.note = None
        self.turns = []

    # -- one daemon's turn -----------------------------------------------

    def start(self, daemon: str) -> None:
        with mock.patch.object(support, "DAEMON_CMD", DAEMONS[daemon]):
            self.box.start()
        self.turns.append(daemon)

    def dispatch(self, ticket_id: str, repo: Path) -> dict:
        body = {"ticket_id": ticket_id, "repo_path": str(repo)}
        if repo == self.artifact:
            body["project_scope_token"] = self.box.scope_token(repo)
        response = self.box.post("/v1/runs", body)
        self.assertEqual(response.status, 202, response)
        return self.box.wait_for_run(response.json["run"]["id"], "Merged")

    def runs(self) -> dict:
        response = self.box.get("/v1/runs", limit=100)
        self.assertEqual(response.status, 200, response)
        return {run["id"]: (run["ticket_id"], run["state"], run["attempt"]) for run in response.json["runs"]}

    def turn(self, daemon: str, step: int, before: dict) -> dict:
        """Start `daemon` on what the previous one left; check and extend it."""
        schema_before = schemas(self.box.data_root)
        self.start(daemon)
        label = " -> ".join(self.turns)

        # What the previous daemon wrote is served unchanged.
        self.assertEqual(self.runs(), before, label)
        for name, schema in schema_before.items():
            self.assertEqual(schemas(self.box.data_root).get(name), schema, "%s migrated %s" % (label, name))
        if self.session is not None:
            again = self.box.post("/v1/orchestrator-session/ensure",
                                  {"repo_path": str(self.legacy), "provider": self.agent})
            self.assertEqual(again.status, 200, again)
            self.assertEqual(again.json["orchestrator_session"]["id"], self.session, label)
        if self.note is not None:
            note = self.box.get("/v1/artifacts/notes/%s" % self.note)
            self.assertEqual(note.status, 200, note)
            self.assertEqual(note.json["note"]["identity"]["note_id"], self.note, label)

        # And it carries on from there.
        legacy = self.dispatch("CT-%d" % step, self.legacy)
        artifact = self.dispatch("CT-%d" % (10 + step), self.artifact)
        previous = max(before, default=0)
        self.assertEqual((legacy["id"], artifact["id"]), (previous + 1, previous + 2), label)
        self.assertIn("\nstatus: done\n", (self.legacy / ".orchestrator" / ("CT-%d.md" % step)).read_text())
        self.assertIn(
            "status: done",
            git(self.artifact, "show", "%s:.orchestrator/CT-%d.md" % (ARTIFACT_REF, 10 + step)),
        )
        if self.session is None:
            created = self.box.post("/v1/orchestrator-session/ensure",
                                    {"repo_path": str(self.legacy), "provider": self.agent})
            self.assertEqual(created.status, 201, created)
            self.session = created.json["orchestrator_session"]["id"]
        if self.note is None:
            created = self.box.post("/v1/artifacts/notes/create", create_body("swap-%s" % daemon))
            self.assertEqual(created.status, 201, created)
            self.note = created.json["note"]["identity"]["note_id"]

        after = self.runs()
        self.box.stop()
        return after

    def swap(self, *order: str) -> None:
        runs = {}
        for step, daemon in enumerate(order, start=1):
            runs = self.turn(daemon, step, runs)
        self.assertEqual(sorted(state for _, state, _ in runs.values()), ["Merged"] * 2 * len(order))

    def test_python_then_rust_then_python(self):
        self.swap("python", "rust", "python")

    def test_rust_then_python_then_rust(self):
        self.swap("rust", "python", "rust")


class ClaudeDaemonSwapTests(_SwapCase):
    agent = "claude"


class CodexDaemonSwapTests(_SwapCase):
    agent = "codex"


del _SwapCase


if __name__ == "__main__":
    unittest.main()
