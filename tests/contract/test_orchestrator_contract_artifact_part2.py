"""RR-495: the RR-485 migration, retention, archival and history cases on Rust.

Two halves:

- ``RustMigrated*`` repeat the board and retention daemon cases with the
  product migration command replaced by ``relay-rs artifact-migrate`` (the
  Rust port). The bootstrap commit and source cutover must match golden
  ``board/1-bootstrap``, and the reference Python daemon then serves the
  Rust-migrated project through every later golden: board writes,
  retention preview and status, the refused apply, history search and the
  dependency summary. This is the two implementations alternating on one
  repository with no migration between them.
- ``RustRetentionGoldenCase`` computes the retention preview and status
  bodies, the refused local-only archive and the history search with the
  Rust crate alone, through rust/relay-artifacts/examples/artifacts_driver.rs,
  and compares them with the same goldens.

Every case skips when the Rust binaries are not built (``cargo build`` in
rust/) and when goldens are being regenerated, since the reference daemon
owns them.
"""

from __future__ import annotations

import os
import sys
import unittest
from pathlib import Path
from unittest import mock

import orchestrator_contract_support as support
from orchestrator_contract_support import ARTIFACT_REF, UPDATE_GOLDEN, Sandbox, git

import test_orchestrator_contract_board as board_cases
import test_orchestrator_contract_notes as notes_cases

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from relay_artifacts_support import REPO, Refused, RustArtifacts, driver_command  # noqa: E402

CLI_BINARY = REPO / "rust" / "target" / "debug" / "relay-rs"
# The Program/Graphify step runs in-process (RR-487).
RUST_MIGRATION = [str(CLI_BINARY), "artifact-migrate"]


def _require_rust(test_case_class) -> None:
    if UPDATE_GOLDEN:
        raise unittest.SkipTest("goldens are being regenerated by the reference daemon")
    if not os.access(CLI_BINARY, os.X_OK):
        raise unittest.SkipTest("relay-rs is not built; run cargo build in rust/")


class _RustMigration:
    """Runs a daemon case class with the Rust migration command."""

    @classmethod
    def setUpClass(cls):
        _require_rust(cls)
        patcher = mock.patch.object(support, "MIGRATION_CMD", RUST_MIGRATION)
        patcher.start()
        cls.addClassCleanup(patcher.stop)
        super().setUpClass()


class RustMigratedBoardTests(_RustMigration, board_cases.GoldenBoardTests):
    """Golden board writes on a project the Rust migration created."""


class RustMigratedRetentionTests(_RustMigration, notes_cases.RetentionTests):
    """Retention and history on a 27-ticket project the Rust migration created."""


class RustRetentionGoldenCase(unittest.TestCase):
    """The retention goldens, computed by the Rust crate alone."""

    maxDiff = None

    @classmethod
    def setUpClass(cls):
        _require_rust(cls)
        command = driver_command()
        if not command:
            raise unittest.SkipTest("relay-artifacts driver is not built; run cargo test in rust/")
        cls.box = Sandbox(cls.addClassCleanup)
        patcher = mock.patch.object(support, "MIGRATION_CMD", RUST_MIGRATION)
        patcher.start()
        try:
            cls.repo = cls.box.artifact_project("retained", tickets=[
                ("CT-%d" % number, {"status": "done"}) for number in range(1, 28)
            ], next_id=28)
        finally:
            patcher.stop()
        cls.crate = RustArtifacts(command, environment={"GIT_CONFIG_NOSYSTEM": "1"})
        cls.addClassCleanup(cls.crate.close)
        project_id = cls.box.registry_record(cls.repo)["project_id"]
        cls.crate.call("store.open", repo=str(cls.repo), project_id=project_id,
                       state_root=str(cls.box.state_root))

    def retention(self, function: str, **arguments):
        return self.crate.call(
            "retention." + function, remote_mode="local_only", synchronizer=False,
            enabled=True, **arguments,
        )

    def test_migration_matches_the_bootstrap_golden_shape(self):
        self.assertEqual(git(self.repo, "ls-files", ".orchestrator"), "")
        self.assertEqual(
            git(self.repo, "log", "-1", "--format=%s"), "Stop tracking Relay artifact materialization",
        )
        self.assertEqual(git(self.repo, "rev-list", "--count", ARTIFACT_REF), "1")
        self.assertEqual(git(self.repo, "status", "--porcelain", "--untracked-files=all"), "")

    def test_preview_and_status_match_the_goldens(self):
        preview = self.retention("preview")
        self.assertEqual(preview["limit"], 25)
        self.assertEqual(preview["eviction_candidate_ids"], ["CT-2", "CT-1"])
        self.box.assert_golden_json("retention/preview.response", preview)
        status = self.retention("status")
        self.assertEqual(status["state"], "blocked")
        self.assertEqual(status["remote_mode"], "local_only")
        self.box.assert_golden_json("retention/status.response", status)

    def test_local_only_archive_is_refused_and_writes_nothing(self):
        head = git(self.repo, "rev-parse", ARTIFACT_REF)
        with self.assertRaises(Refused) as refused:
            self.retention("archive", event_id="r-1", device_id="contract")
        self.assertIn(
            "terminal cleanup remains preview-only until a GitHub remote is selected and confirmed",
            refused.exception.message,
        )
        self.assertEqual(git(self.repo, "rev-parse", ARTIFACT_REF), head)
        self.assertTrue((self.repo / ".orchestrator" / "CT-1.md").exists())

    def test_history_search_finds_nothing_archived(self):
        self.assertEqual(self.retention("history_search", query="CT-1")["history"], [])


if __name__ == "__main__":
    unittest.main()
