"""RR-497/RR-498: the RR-485 daemon contract suite against the Rust daemon.

Every daemon case class of the suite is repeated here with the daemon
command replaced by ``rust/target/debug/relay-orchestrator`` (or
``RELAY_RUST_ORCHESTRATOR``), so one run checks both daemons. The
``RustMigrated*`` classes of RR-495 are repeated as well, which puts a Rust
migration and a Rust daemon on the same repository. Worker, review, spike and
restart cases run like every other case since RR-498 ported execution.

Every case skips when the binary is not built (``cargo build`` in rust/) and
while goldens are being regenerated, since the reference daemon owns them.
"""

from __future__ import annotations

import os
import unittest
from pathlib import Path
from unittest import mock

import orchestrator_contract_support as support
from orchestrator_contract_support import UPDATE_GOLDEN

import test_orchestrator_contract_artifact_part2 as part2_cases
import test_orchestrator_contract_artifact_runs as artifact_run_cases
import test_orchestrator_contract_board as board_cases
import test_orchestrator_contract_lifecycle as lifecycle_cases
import test_orchestrator_contract_notes as notes_cases
import test_orchestrator_contract_routes as route_cases
import test_orchestrator_contract_runs as run_cases
import test_orchestrator_contract_sessions as session_cases

REPO = Path(__file__).resolve().parents[2]
RUST_DAEMON = Path(
    os.environ.get("RELAY_RUST_ORCHESTRATOR")
    or REPO / "rust" / "target" / "debug" / "relay-orchestrator"
)


class _RustDaemon:
    """Runs a case class with the Rust daemon command."""

    @classmethod
    def setUpClass(cls):
        if UPDATE_GOLDEN:
            raise unittest.SkipTest("goldens are being regenerated by the reference daemon")
        if not os.access(RUST_DAEMON, os.X_OK):
            raise unittest.SkipTest("relay-orchestrator is not built; run cargo build in rust/")
        patcher = mock.patch.object(support, "DAEMON_CMD", [str(RUST_DAEMON)])
        patcher.start()
        cls.addClassCleanup(patcher.stop)
        super().setUpClass()


def _rust_case(base: type) -> type:
    attributes = {"__doc__": "%s against the Rust daemon." % base.__name__,
                  "__module__": __name__}
    return type("Rust" + base.__name__, (_RustDaemon, base), attributes)


