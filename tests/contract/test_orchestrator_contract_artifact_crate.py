"""RR-494: commits made by the relay-artifacts crate against the RR-485 goldens.

Each golden commit under golden/orchestrator/{board,artifact-runs,notes} was
made by the reference daemon. This case rebuilds every one with the Rust
crate alone: the operations are the difference between a golden tree and the
one before it, with the documented placeholders replaced by fixed values;
the summary, event, device, actor and provider come from the golden message
(tests/relay_artifacts_support.py, ``replay_golden``). Each resulting commit
is then compared by the suite's own ``Sandbox.assert_golden_commit``, byte for
byte after normalisation.

It drives rust/relay-artifacts/examples/artifacts_driver.rs and imports
nothing from services/. It skips when the driver is not built (``cargo test``
in rust/ builds it) and when goldens are being regenerated, since the
reference daemon owns them.
"""

from __future__ import annotations

import sys
import unittest
from pathlib import Path

from orchestrator_contract_support import (
    ARTIFACT_REF, GIT_IDENTITY, UPDATE_GOLDEN, Sandbox, git,
)

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from relay_artifacts_support import (  # noqa: E402
    GOLDEN_SEQUENCES, RustArtifacts, driver_command, golden_commit, replay_golden,
)


@unittest.skipIf(UPDATE_GOLDEN, "goldens are being regenerated by the reference daemon")
class ArtifactCrateGoldenCase(unittest.TestCase):
    def setUp(self):
        command = driver_command()
        if not command:
            self.skipTest("relay-artifacts driver is not built; run cargo test in rust/")
        self.box = Sandbox(self.addCleanup)
        isolation = {"GIT_CONFIG_GLOBAL": "/dev/null", "GIT_CONFIG_NOSYSTEM": "1"}
        self.crate = RustArtifacts(command, environment=isolation)
        self.addCleanup(self.crate.close)

    def repo(self, name: str) -> Path:
        repo = self.box.root / name
        repo.mkdir()
        git(repo, "init", "--initial-branch=main", "--quiet")
        (repo / "README.md").write_text("# Contract project\n")
        git(repo, "add", "README.md")
        git(repo, "-c", "commit.gpgsign=false", "commit", "--quiet", "-m", "chore: initial project",
            env=GIT_IDENTITY)
        return repo

    def test_crate_commits_match_the_goldens(self):
        for group, names in GOLDEN_SEQUENCES:
            repo = self.repo("%s-%s" % (group, names[0]))
            project_id = golden_commit("%s/%s" % (group, names[0]))["trailers"]["Relay-Project-ID"]
            self.crate.call("store.open", repo=str(repo), project_id=project_id,
                            state_root=str(self.box.state_root))

            def check(name, files, _result, repo=repo, group=group):
                with self.subTest(golden="%s/%s" % (group, name)):
                    self.box.assert_golden_commit("%s/%s" % (group, name), repo)
                    # The projection holds the commit's files; the source
                    # branch is untouched.
                    self.assertEqual(
                        sorted(str(path.relative_to(repo)) for path in
                               (repo / ".orchestrator").rglob("*") if path.is_file()),
                        sorted(files),
                    )
                    self.assertEqual(git(repo, "rev-parse", "--abbrev-ref", "HEAD"), "main")
                    self.assertEqual(git(repo, "status", "--porcelain"), "")

            replay_golden(self.crate.call, repo, group, names, check)
            git(repo, "rev-parse", "--verify", ARTIFACT_REF)


if __name__ == "__main__":
    unittest.main()
