"""RR-499: the RR-485 notes and personal-storage cases against relay-services.

`test_orchestrator_contract_notes.py` (NoteLifecycleTests, NoteErrorTests)
and `PersonalStorageTests` in `test_orchestrator_contract_sessions.py` drive
the reference daemon over HTTP. The Rust daemon's HTTP layer is a later part
of the port, so these cases replay the same steps through the library the
routes will call: rust/relay-services/examples/notes_driver.rs, run inside
the suite's sandbox with its fake `claude` and `gh` on PATH. Commits and
responses are compared with the same goldens and normalisation, and errors
carry the Python class each route maps to a status (ValueError and
NoteContractError 400, ArtifactValidationError 422, StorageError 409).

It imports nothing from services/. It skips when the driver is not built
(`cargo test` in rust/ builds it) and when goldens are being regenerated,
since the reference daemon owns them.
"""

from __future__ import annotations

import base64
import json
import os
import shlex
import subprocess
import unittest
from pathlib import Path

from orchestrator_contract_support import ARTIFACT_REF, REPO_ROOT, UPDATE_GOLDEN, Sandbox, git

DEFAULT_DRIVER = REPO_ROOT / "rust" / "target" / "debug" / "examples" / "notes_driver"
DEVICE_ID = "daemon-0123456789abcdef01234567"

T0 = "2026-08-04T05:00:00Z"
T1 = "2026-08-04T05:01:00Z"
FIRST = {"segment_id": "s1", "captured_at": T0, "text": "We decided to ship the contract suite.",
         "start_ms": 0, "end_ms": 1200, "speaker": None}
SECOND = {"segment_id": "s2", "captured_at": T1, "text": "The port follows next quarter.",
          "start_ms": 1200, "end_ms": 2000, "speaker": None}

# The status each route gives an error class (services/orchestrator.py).
STATUS = {"ArtifactValidationError": 422, "StorageError": 409, "ValueError": 400,
          "NoteContractError": 400}


def driver_command() -> list | None:
    configured = os.environ.get("RELAY_SERVICES_NOTES_DRIVER", "").strip()
    if configured:
        return shlex.split(configured)
    if os.access(DEFAULT_DRIVER, os.X_OK):
        return [str(DEFAULT_DRIVER)]
    return None


class Refused(Exception):
    def __init__(self, answer: dict):
        super().__init__("%s: %s" % (answer["error"], answer["message"]))
        self.error = answer["error"]
        self.message = answer["message"]
        self.state = answer.get("state")


class Driver:
    def __init__(self, command: list, environment: dict):
        self._process = subprocess.Popen(
            command, stdin=subprocess.PIPE, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
            text=True, bufsize=1, env=environment,
        )

    def call(self, op: str, **arguments):
        self._process.stdin.write(json.dumps({"op": op, **arguments}) + "\n")
        self._process.stdin.flush()
        line = self._process.stdout.readline()
        if not line:
            raise RuntimeError("notes driver exited: %s" % self._process.stderr.read())
        answer = json.loads(line)
        if not answer["ok"]:
            raise Refused(answer)
        return answer["result"]

    def close(self) -> None:
        if self._process.poll() is None:
            self._process.stdin.close()
            try:
                self._process.wait(timeout=10)
            except subprocess.TimeoutExpired:
                self._process.kill()
                self._process.wait()
        self._process.stdout.close()
        self._process.stderr.close()


def create_body(request_id: str, **overrides) -> dict:
    body = {
        "request_id": request_id, "created_at": T0, "capture_started_at": T0,
        "captured_at": T0, "recording_state": "recording", "checkpoint_reason": "checkpoint",
        "segments": [FIRST], "capture_ended_at": None, "provider": "claude",
    }
    body.update(overrides)
    return body


@unittest.skipIf(UPDATE_GOLDEN, "goldens are being regenerated by the reference daemon")
class CrateCase(unittest.TestCase):
    def setUp(self):
        command = driver_command()
        if not command:
            self.skipTest("relay-services notes driver is not built; run cargo test in rust/")
        self.box = Sandbox(self.addCleanup)
        self.driver = Driver(command, self.box.environment())
        self.addCleanup(self.driver.close)
        general = {"provider": self.box.agent, "command": str(self.box.bin / self.box.agent)}
        self.driver.call("open", state_root=str(self.box.state_root), device_id=DEVICE_ID,
                         config={"general": general})

    @property
    def notes_repo(self) -> Path:
        return self.box.state_root / "notes"

    def assertRefused(self, status: int, fragment: str, op: str, **arguments) -> Refused:
        with self.assertRaises(Refused) as caught:
            self.driver.call(op, **arguments)
        self.assertEqual(STATUS.get(caught.exception.error), status, str(caught.exception))
        self.assertIn(fragment, caught.exception.message)
        return caught.exception

    def note(self, identity: str) -> dict:
        return self.driver.call("get", identity=identity)

    def wait_for_metadata(self, note_id: str, predicate) -> dict:
        self.driver.call("wait_idle")
        note = self.note(note_id)
        self.assertTrue(predicate(note["note"]["metadata"]), note["note"]["metadata"])
        return note


class NoteLifecycleCrateTests(CrateCase):
    def test_note_lifecycle_commits_the_golden_trees(self):
        created = self.driver.call("create", **create_body("c-1"))
        identity = created["note"]["identity"]
        self.assertEqual(identity["note_id"], "RR-N1")
        self.assertEqual(identity["project_id"], "global-notes")
        self.assertIs(created["idempotent"], False)
        self.assertEqual(created["note"]["metadata"]["state"], "pending")
        self.assertEqual(
            base64.b64decode(created["markdown_base64"]),
            git(self.notes_repo, "show", "%s:.orchestrator/notes/RR-N1.md" % ARTIFACT_REF,
                binary=True),
        )
        self.box.assert_golden_json("notes/create.response", created)
        self.box.assert_golden_commit("notes/1-create", self.notes_repo)

        # Repeating the request is idempotent and writes nothing.
        head = git(self.notes_repo, "rev-parse", ARTIFACT_REF)
        again = self.driver.call("create", **create_body("c-1"))
        self.assertIs(again["idempotent"], True)
        self.assertEqual(again["note"]["identity"], identity)
        self.assertEqual(git(self.notes_repo, "rev-parse", ARTIFACT_REF), head)

        update = {
            "identity": identity, "captured_at": T1, "recording_state": "completed",
            "checkpoint_reason": "complete", "segments": [FIRST, SECOND], "capture_ended_at": T1,
        }
        updated = self.driver.call("update", note_id="RR-N1", request_id="u-1", update=update,
                                   provider="claude")
        self.assertEqual(updated["note"]["recording_state"], "completed")
        self.assertEqual(len(updated["note"]["segments"]), 2)

        ready = self.wait_for_metadata("RR-N1", lambda metadata: metadata["state"] == "ready")
        metadata = ready["note"]["metadata"]
        self.assertEqual(metadata["title"], "Scripted note title")
        self.assertEqual(metadata["summary"], "A scripted summary of the captured note.")
        self.assertEqual(metadata["provider"], "claude")
        self.assertEqual(metadata["source_sha256"], metadata["generated_source_sha256"])
        self.box.assert_golden_commit("notes/2-metadata", self.notes_repo)
        launch = self.box.invocations(role="note-metadata")[0]
        self.assertEqual(launch["stdin_keys"], ["relay_captured_transcript"])
        self.assertEqual(launch["argv"][:2], ["--print", "--safe-mode"])
        # The subscription-only gate ran before the launch.
        self.assertTrue(self.box.invocations(role="auth"))

        # The same note answers by note id and by artifact id.
        self.assertEqual(self.note(identity["artifact_id"])["note"], ready["note"])
        listed = self.driver.call("list")
        self.assertEqual([item["note_id"] for item in listed["notes"]], ["RR-N1"])
        self.assertEqual(listed["total_count"], 1)
        self.assertIs(listed["has_more"], False)
        self.box.assert_golden_json("notes/list.response", listed)

        # A retry regenerates metadata from the same source.
        self.box.plan("note-metadata", result={"title": "Retried title", "summary": "Retried summary."})
        retried = self.driver.call("retry_metadata", note_id="RR-N1")
        self.assertEqual(retried["note"]["metadata"]["state"], "pending")
        self.wait_for_metadata("RR-N1", lambda metadata: metadata.get("title") == "Retried title")

        archived = self.driver.call("archive", note_id="RR-N1", artifact_id=identity["artifact_id"],
                                    archived_at=T1, request_id="a-1", provider="claude")
        self.box.assert_golden_json("notes/archive.response", archived)
        self.box.assert_golden_commit("notes/3-archive", self.notes_repo)

        deleted = self.driver.call("delete", note_id="RR-N1", artifact_id=identity["artifact_id"],
                                   request_id="d-1")
        self.assertIs(deleted["deleted"], True)
        self.box.assert_golden_commit("notes/4-delete", self.notes_repo)
        self.assertEqual(self.driver.call("list")["notes"], [])


class NoteErrorCrateTests(CrateCase):
    def test_create_requires_a_request_id(self):
        self.assertRefused(422, "note request_id must be 1 to 120 safe characters",
                           "create", **create_body(""))

    def test_unknown_and_malformed_note_ids(self):
        self.assertRefused(422, "no unique project note matches", "get", identity="RR-N404")
        self.assertRefused(400, "invalid unpadded note ID: 'not-a-note'", "delete",
                           note_id="not-a-note", artifact_id="", request_id="")

    def test_update_needs_an_object(self):
        self.assertRefused(400, "note update must be an object", "update",
                           note_id="RR-N1", request_id="", update="x")

    def test_cancel_discards_a_recording(self):
        created = self.driver.call("create", **create_body("cancel-1"))
        identity = created["note"]["identity"]
        canceled = self.driver.call("cancel", note_id=identity["note_id"],
                                    artifact_id=identity["artifact_id"], request_id="cancel-2")
        self.assertIs(canceled["deleted"], True)
        listed = self.driver.call("list")["notes"]
        self.assertNotIn(identity["note_id"], [item["note_id"] for item in listed])


class PersonalStorageCrateTests(CrateCase):
    def storage(self, method: str, route: str, payload=None):
        return self.driver.call("storage", method=method, path="/v1/personal-storage/" + route,
                                payload=payload or {})

    def test_local_only_status_files_and_policy(self):
        status = self.storage("GET", "status")
        self.assertEqual((status["state"], status["connected"]), ("local_only", False))
        self.assertEqual(status["files_root"], str(self.box.state_root / "files"))
        self.assertEqual(self.storage("GET", "files"), {"files": []})
        policy = self.storage("POST", "policy", {"budget_bytes": 128 * 1024 * 1024, "retention_days": 7})
        self.assertEqual((policy["budget_bytes"], policy["retention_days"]), (128 * 1024 * 1024, 7))
        refused = self.assertRefused(
            409, "Enable private GitHub storage explicitly before creating a repository.",
            "storage", method="POST", path="/v1/personal-storage/configure", payload={},
        )
        self.assertEqual(refused.state, "local_only")
        # The account lookup asks gh, which the fake answers as signed out.
        self.assertRefused(409, "GitHub", "storage", method="GET",
                           path="/v1/personal-storage/account", payload={})
        self.assertTrue(self.box.invocations(role="gh"))


if __name__ == "__main__":
    unittest.main()
